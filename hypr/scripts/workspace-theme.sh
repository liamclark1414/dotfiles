#!/usr/bin/env bash
# Travel through Middle-earth: each workspace restyles the desktop.
#   wallpaper (hyprpaper) · terminal colours (kitty) · bar (Waybar) · borders (Hyprland)
# Workspaces 6-9 have no place of their own: Bag End palette + moonlit wallpaper.

PICS="$HOME/Pictures"
KITTY="$HOME/.config/kitty"
WAYBAR="$HOME/.config/waybar"
DEFAULT_WALL="$PICS/lotr_desktop_wallpaper_2.jpg"

declare -A PLACE=( [1]=bag_end [2]=bree [3]=rivendell [4]=moria [5]=lorien )

# read "colorN" (or any key) from a kitty theme file → hex without '#'
get() { awk -v k="$1" '$1==k {sub("#","",$2); print $2; exit}' "$2"; }

apply() {
    local ws="$1" place="${PLACE[$1]:-bag_end}"
    local theme="$KITTY/themes/$place.conf"

    # ─ wallpaper ─
    local img="$PICS/$place.jpg"
    [[ -n "${PLACE[$ws]:-}" ]] || img="$DEFAULT_WALL"
    file -b --mime-type "$img" 2>/dev/null | grep -q '^image/' || img="$DEFAULT_WALL"
    hyprctl hyprpaper wallpaper ",$img" >/dev/null

    # palette unchanged? skip the restyle
    [[ "$place" == "${CURRENT:-}" ]] && return
    CURRENT="$place"

    # ─ kitty: new windows (symlink) + running ones (remote control) ─
    ln -sfn "themes/$place.conf" "$KITTY/current-theme.conf"
    for sock in "$XDG_RUNTIME_DIR"/kitty-*; do
        [[ -S "$sock" ]] || continue
        kitten @ --to "unix:$sock" set-colors --all --configured "$theme" 2>/dev/null \
            || { rm -f "$sock"; continue; }
        kitten @ --to "unix:$sock" set-background-opacity --all "$(get background_opacity "$theme")" 2>/dev/null
    done

    # ─ Waybar: regenerate colours, then hot-reload ─
    cat > "$WAYBAR/current.css" <<CSS
/* generated by workspace-theme.sh from kitty/themes/$place.conf */
@define-color forest     #$(get background "$theme");
@define-color moss       #$(get color0 "$theme");
@define-color stone      #$(get color8 "$theme");
@define-color parchment  #$(get foreground "$theme");
@define-color hearth     #$(get color3 "$theme");
@define-color ring       #$(get color11 "$theme");
@define-color hills      #$(get color2 "$theme");
@define-color leaf       #$(get color1 "$theme");
@define-color brandywine #$(get color4 "$theme");
@define-color heather    #$(get color5 "$theme");
@define-color rivendell  #$(get color6 "$theme");
CSS
    pkill -SIGUSR2 -x waybar

    # ─ Rofi: same colours for the launcher ─
    cat > "$HOME/.config/rofi/current.rasi" <<RASI
/* generated by workspace-theme.sh from kitty/themes/$place.conf */
* {
    forest:    #$(get background "$theme");
    moss:      #$(get color0 "$theme");
    stone:     #$(get color8 "$theme");
    parchment: #$(get foreground "$theme");
    hearth:    #$(get color3 "$theme");
    ring:      #$(get color11 "$theme");
    hills:     #$(get color2 "$theme");
    leaf:      #$(get color1 "$theme");
}
RASI

    # ─ lock screen: colours, wallpaper and place name ─
    declare -A NAME=( [bag_end]="Bag End" [bree]="Bree" [rivendell]="Rivendell" [moria]="Moria" [lorien]="Lórien" )
    cat > "$HOME/.config/hypr/hyprlock-place.conf" <<LOCK
# generated by workspace-theme.sh from kitty/themes/$place.conf
\$wallpaper = $img
\$placename = ${NAME[$place]}
\$bg     = $(get background "$theme")
\$bg_glass = $(get background "$theme")cc
\$text   = $(get foreground "$theme")
\$muted  = $(get color8 "$theme")
\$gold   = $(get color11 "$theme")
\$accent = $(get color2 "$theme")
\$red    = $(get color1 "$theme")
LOCK

    # ─ notifications (mako) ─
    mkdir -p "$HOME/.config/mako"
    cat > "$HOME/.config/mako/config" <<MAKO
# generated by workspace-theme.sh from kitty/themes/$place.conf — edit the script, not this file
font=IosevkaTermSlab Nerd Font 12
anchor=top-right
margin=58,14,0,0
padding=14,16
width=360
border-size=2
border-radius=12
default-timeout=6000
max-visible=4
icons=1
max-icon-size=40
background-color=#$(get background "$theme")ee
text-color=#$(get foreground "$theme")
border-color=#$(get color3 "$theme")
progress-color=over #$(get color2 "$theme")
format=<b>%s</b>\\n%b

[urgency=low]
border-color=#$(get color8 "$theme")

[urgency=critical]
border-color=#$(get color1 "$theme")
default-timeout=0
MAKO
    makoctl reload 2>/dev/null

    # ─ GTK apps (Nautilus etc.): same palette for GTK4 and GTK3 ─
    gtkcolors="/* generated by workspace-theme.sh from kitty/themes/$place.conf */
@define-color me_bg      #$(get background "$theme");
@define-color me_fg      #$(get foreground "$theme");
@define-color me_surface #$(get color0 "$theme");
@define-color me_muted   #$(get color8 "$theme");
@define-color me_gold    #$(get color3 "$theme");
@define-color me_green   #$(get color2 "$theme");
@define-color me_red     #$(get color1 "$theme");"
    printf '%s\n' "$gtkcolors" > "$HOME/.config/gtk-4.0/middle-earth-colors.css"
    printf '%s\n' "$gtkcolors" > "$HOME/.themes/Middle-earth/gtk-3.0/colors.css"

    # ─ Hyprland borders ─
    hyprctl --batch "keyword general:col.active_border rgb($(get color3 "$theme")) rgb($(get color11 "$theme")) rgb($(get color2 "$theme")) 45deg ; keyword general:col.inactive_border rgb($(get color0 "$theme"))" >/dev/null
}

# give hyprpaper and Waybar a moment to start, then style the current workspace
sleep 1
apply "$(hyprctl activeworkspace -j | grep -m1 '"id"' | tr -dc '0-9')"

socat -U - "UNIX-CONNECT:$XDG_RUNTIME_DIR/hypr/$HYPRLAND_INSTANCE_SIGNATURE/.socket2.sock" |
while read -r line; do
    case "$line" in
        workspace\>\>*) apply "${line#workspace>>}" ;;
    esac
done
